export function connectorCategory(serviceID: string) {
  const key = serviceID.toLowerCase().replace(/^mcp:/, "").replaceAll("-", "_");
  return (
    connectorCategories.find(({ services }) => services.includes(key))?.value ??
    "other"
  );
}
