const DISPLAY_COPY = new Map<string, string>();
Object.values(BRAIN_DUMP_PROMPT_SETS).forEach((set, role) => {
  set.questions.forEach((question, index) => {
    const [label, text] = QUESTIONS[role][index].split("：");
    DISPLAY_COPY.set(question.label, label);
    DISPLAY_COPY.set(question.text, text);
  });
  set.examples.forEach((example, index) =>
    DISPLAY_COPY.set(example, EXAMPLES[role][index]),
  );
  DISPLAY_COPY.set(set.offYourPlateExample, OFFLOAD[role]);
});
DISPLAY_COPY.set("For example", "例如");

export function usePromptTranslation() {
  const { t } = useTranslation();

  function translatePrompt(text: string) {
    const chinese = DISPLAY_COPY.get(text);
    if (chinese) return t(text, chinese);
    if (text.startsWith("Like: "))
      return t(
        text,
        `例如：${DISPLAY_COPY.get(text.slice(6)) ?? text.slice(6)}`,
      );
    return text;
  }

  return { translatePrompt };
}
